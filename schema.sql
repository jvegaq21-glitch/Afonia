CREATE DATABASE IF NOT EXISTS kwhtrack_demo CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kwhtrack_demo;

CREATE TABLE IF NOT EXISTS homes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  city VARCHAR(80) NOT NULL DEFAULT 'Cartagena'
);
CREATE TABLE IF NOT EXISTS devices (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  home_id INT UNSIGNED NOT NULL DEFAULT 1,
  name VARCHAR(50) NOT NULL,
  category VARCHAR(40) NOT NULL,
  watts DECIMAL(10,2) NOT NULL,
  hours DECIMAL(4,1) NOT NULL,
  quantity SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  FOREIGN KEY (home_id) REFERENCES homes(id) ON DELETE CASCADE,
  CHECK (watts > 0), CHECK (hours BETWEEN 0 AND 24), CHECK (quantity > 0)
);
CREATE TABLE IF NOT EXISTS bills (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  home_id INT UNSIGNED NOT NULL DEFAULT 1,
  bill_date DATE NOT NULL,
  consumption_kwh DECIMAL(12,2) NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  FOREIGN KEY (home_id) REFERENCES homes(id) ON DELETE CASCADE,
  CHECK (consumption_kwh >= 0), CHECK (amount >= 0)
);
CREATE TABLE IF NOT EXISTS settings (
  id TINYINT UNSIGNED PRIMARY KEY,
  home_id INT UNSIGNED NOT NULL,
  rate DECIMAL(12,2) NOT NULL DEFAULT 1000,
  FOREIGN KEY (home_id) REFERENCES homes(id) ON DELETE CASCADE,
  CHECK (rate > 0)
);
